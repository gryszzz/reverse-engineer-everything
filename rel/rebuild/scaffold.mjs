/** Pack the product directory. The archive is written only when this runs. */
export function packageRebuild(outDir) {
  if (!outDir) throw new Error("An output directory is required.");
  assertOutsideRepo(outDir);
  if (!existsSync(join(outDir, "behavior-spec.json")))
    throw new Error("Nothing to package. The product files are not written.");
  return packageProduct(outDir);
}

function packageProduct(outDir) {
  const archive = join(outDir, "product.tgz");
  rmSync(archive, { force: true });
  const staging = join(
    tmpdir(),
    `ree-${basename(outDir)}-${randomBytes(4).toString("hex")}.tgz`,
  );
  const packed = spawnSync("tar", ["-czf", staging, "-C", outDir, "."], {
    encoding: "utf8",
  });
  if (packed.status !== 0) {
    throw new Error(
      "Could not write product.tgz. " +
        (packed.stderr || packed.error?.message || "tar failed."),
    );
  }
  renameSync(staging, archive);
  return archive;
}

/**
 * Write a clean-room HTTP product from a behavior spec.
 * Original code is neither read nor copied.
 */
export function scaffoldRebuild({
  spec: input,
  productName,
  outDir,
  now = new Date(),
  onEvent,
  pack = true,
  improvements = null,
}) {
  if (typeof productName !== "string" || !productName.trim())
    throw new Error("A new product name is required.");
  const name = productName.trim();
  if (
    name.toLowerCase() ===
    String(input?.target?.name ?? "")
      .trim()
      .toLowerCase()
  )
    throw new Error(
      "The new product name must differ from the spec target name.",
    );
  const spec = assertValidBehaviorSpec(input);
  if (!outDir) throw new Error("An output directory is required.");
  assertOutsideRepo(outDir);
  const leaked = quotesIn(spec).find((quote) => name.includes(quote));
  if (leaked) throw new Error("The product name contains a spec quote.");
  const plan = planProduct(spec);
  const capabilities = decideCapabilities(spec, plan, improvements);
  const readme = readmeText(name, spec, plan, capabilities);
  const landing = landingText(name, spec, plan, capabilities);
  const report = reportText(name, spec, plan, capabilities);
  const brand = String(spec.target.name ?? "").trim();
  if (
    brand &&
    [readme, landing, report, NOTICE_TEXT].some((text) => text.includes(brand))
  )
    throw new Error("Customer copy includes the spec target name.");
  const repeated = quotesIn(spec).find(
    (quote) =>
      readme.includes(quote) ||
      landing.includes(quote) ||
      report.includes(quote) ||
      NOTICE_TEXT.includes(quote),
  );
  if (repeated) throw new Error("Customer copy repeats a spec quote.");
  const specBytes = JSON.stringify(spec);
  const specSha = createHash("sha256").update(specBytes).digest("hex");
  const buildId = "bld_" + randomBytes(8).toString("hex");
  const provenance = {
    schema_version: REBUILD_SCHEMA,
    build_id: buildId,
    generated_at: now.toISOString(),
    product_name: name,
    spec_schema: spec.schema_version,
    spec_sha256: specSha,
    spec_target_recorded_in: "provenance.json",
    clean_room: true,
    clean_room_statement: spec.clean_room_statement,
    original_code_viewed: false,
    original_code_copied: false,
    similarity: spec.similarity,
    sources: spec.sources.map((source) => ({
      url: source.url,
      role: source.role,
      fetched_at: source.fetched_at,
      sha256: source.sha256,
    })),
    generator: "ree-rebuild",
    package_file: "product.tgz",
    implemented_feature_ids: plan.behaviors
      .filter((item) => item.status === "implemented")
      .map((item) => item.id),
    unimplemented_feature_ids: plan.behaviors
      .filter((item) => item.status !== "implemented")
      .map((item) => item.id),
    omitted_feature_ids: plan.omitted,
    left_out: plan.leftOut,
    generator_limits: [
      "Each feature gets a data model, write rules, CRUD routes, a page section, and a behavior test.",
      "A feature whose name equals an endpoint summary or operation id uses that concrete path.",
      "A feature with no matching endpoint gets its own collection.",
      "Declared GET, POST, PUT, PATCH, and DELETE endpoints are built even when no feature name matches.",
      "Records are stored in data/store.sqlite when a record route is built. GET / is the product page. JSON field objects are accepted.",
      "A path with one {name} segment gets get, update, and delete on the parent collection. Other path templates are not expanded.",
      "Login and logout paths hash passwords and issue or revoke a token. findBy paths filter a collection. An inventory path counts a sibling collection.",
      "Stripe checkout and webhook checks are generated for an existing account. They stay off until STRIPE_SECRET_KEY, STRIPE_WEBHOOK_SECRET, and an existing price id are set. No account or product is created. A test key can smoke-check checkout. Live mode stays off unless that deploy sets REE_BILLING_MODE=live and REE_BILLING_LIVE_APPROVED=yes.",
      "GraphQL operations, workflows, and rate limits are not built.",
      "An improvement is an extra feature only when a Scout, Scale, or build pick records a quote. That quote is not copied into the product source.",
    ],
  };
  const manifest = {
    name: slug(name),
    private: true,
    type: "module",
    description:
      "Clean-room HTTP product generated by REE. No original source was copied.",
    scripts: {
      test: "node --test",
      start: "node src/server.mjs",
    },
    license: "MIT",
  };
  const lock = {
    name: manifest.name,
    lockfileVersion: 3,
    requires: true,
    packages: { "": { name: manifest.name, license: "MIT" } },
  };
  const emit = (event) => {
    if (typeof onEvent === "function") onEvent(event);
  };
  for (const behavior of plan.behaviors)
    emit({
      source: "rebuild",
      phase: "spec-item",
      feature_id: behavior.id,
      status: behavior.status,
      message: `Spec item ${behavior.id} is ${behavior.status}.`,
    });
  for (const id of plan.omitted)
    emit({
      source: "rebuild",
      phase: "spec-item",
      feature_id: id,
      status: "omitted",
      message: `Spec item ${id} was omitted because a quote would leak into the product.`,
    });
  mkdirSync(join(outDir, "src"), { recursive: true });
  mkdirSync(join(outDir, "test"), { recursive: true });
  rmSync(join(outDir, "test/accounted.test.mjs"), { force: true });
  const write = (relativePath, contents) => {
    writeFileSync(join(outDir, relativePath), contents);
    emit({
      source: "rebuild",
      phase: "file",
      file: relativePath,
      message: `Wrote ${relativePath}.`,
    });
  };
  write("package.json", JSON.stringify(manifest, null, 2) + "\n");
  write("package-lock.json", JSON.stringify(lock, null, 2) + "\n");
  write("README.md", readme);
  write("LANDING.md", landing);
  write("LICENSE", LICENSE_TEXT);
  write("NOTICE", NOTICE_TEXT);
  write("PRICING.md", pricingText(spec, capabilities));
  write("FEATURE_REPORT.md", report);
  if (improvements)
    write("improvements.json", JSON.stringify(improvements, null, 2) + "\n");
  write(
    "coverage.json",
    JSON.stringify(plannedCoverage(plan, spec.features.length), null, 2) + "\n",
  );
  write(
    "src/behaviors.mjs",
    [
      "// Generated by REE rebuild.",
      "// Ids, status, and handler keys only. Names and quotes are not stored.",
      "export const behaviors = " +
        JSON.stringify(plan.behaviors, null, 2) +
        ";",
      "",
    ].join("\n"),
  );
  write(
    "src/routes.mjs",
    [
      "// Generated by REE rebuild.",
      "// Method, path, operation id, parameter names, body kind, and status only.",
      "export const routes = " + JSON.stringify(plan.routes, null, 2) + ";",
      "",
    ].join("\n"),
  );
  write("src/server.mjs", serverSource(name));
  write("src/capabilities.mjs", capabilitiesSource(capabilities));
  write(
    "capabilities.json",
    JSON.stringify(capabilityReport(capabilities), null, 2) + "\n",
  );
  if (capabilities.openapi)
    write("openapi.json", openApiDocument(name, plan, capabilities));
  if (capabilities.deploy) {
    write("Dockerfile", dockerText());
    write("render.yaml", renderText());
    write(".env.example", envExampleText());
    write(".gitignore", productGitignore());
  }
  write("test/product.test.mjs", TEST_SOURCE);
  write("behavior-spec.json", JSON.stringify(spec, null, 2) + "\n");
  write("provenance.json", JSON.stringify(provenance, null, 2) + "\n");
  write(
    "PROVENANCE.md",
    [
      "# Provenance",
      "",
      provenance.clean_room_statement,
      "",
      "Original code viewed: no",
      "Original code copied: no",
      `Spec sha256: ${specSha}`,
      `Similarity flagged: ${spec.similarity.flagged ? "yes" : "no"}`,
      `Package file: ${provenance.package_file}`,
      "The tarball is added after these files are packed, so the archive does not contain product.tgz.",
      "",
      "Implemented feature ids:",
      ...(provenance.implemented_feature_ids.length
        ? provenance.implemented_feature_ids.map((id) => `- ${id}`)
        : ["- none"]),
      "",
      "Unimplemented feature ids:",
      ...(provenance.unimplemented_feature_ids.length
        ? provenance.unimplemented_feature_ids.map((id) => `- ${id}`)
        : ["- none"]),
      "",
      "Sources:",
      ...provenance.sources.map((item) => `- ${item.url} (${item.fetched_at})`),
      "",
    ].join("\n"),
  );
  let packagePath = null;
  if (pack) {
    packagePath = packageProduct(outDir);
    emit({
      source: "rebuild",
      phase: "package",
      file: "product.tgz",
      message: "Wrote product.tgz.",
    });
  }
  return {
    build_id: buildId,
    out_dir: outDir,
    provenance,
    feature_count: spec.features.length,
    implemented_count: provenance.implemented_feature_ids.length,
    unimplemented_count: provenance.unimplemented_feature_ids.length,
    package_path: packagePath,
  };
}

function capabilitiesSource(decision) {
  const runtime = {
    storage: decision.storage,
    relations: decision.relations,
    search: decision.search,
    auth: decision.auth,
    roles: decision.roles,
    webhooks: decision.webhooks,
    pricing: decision.pricing,
    openapi: decision.openapi,
    deploy: decision.deploy,
  };
  return (
    "// Generated by REE rebuild.\n" +
    "// Capability switches only. Spec quotes are not stored.\n" +
    "export const capabilities = " +
    JSON.stringify(runtime, null, 2) +
    ";\n"
  );
}

function openApiDocument(name, plan, capabilities) {
  const paths = {};
  for (const route of plan.routes) {
    paths[route.path] ??= {};
    const operation = {
      responses: {
        [String(route.success_status)]: { description: route.action },
      },
    };
    if (route.operation_id) operation.operationId = route.operation_id;
    paths[route.path][route.method.toLowerCase()] = operation;
  }
  if (capabilities.pricing) {
    paths["/pricing"] = {
      get: { responses: { 200: { description: "pricing page" } } },
    };
    paths["/billing"] = {
      get: { responses: { 200: { description: "billing setup status" } } },
    };
    paths["/checkout"] = {
      post: {
        responses: {
          200: { description: "test checkout or unconfigured" },
          400: { description: "live key not approved" },
        },
      },
    };
    paths["/billing/webhook"] = {
      post: {
        responses: {
          200: { description: "signature accepted or billing disabled" },
          400: { description: "signature rejected" },
        },
      },
    };
  }
  if (capabilities.webhooks) {
    paths["/webhooks"] = {
      get: { responses: { 200: { description: "stored events" } } },
      post: {
        responses: { 201: { description: "stored locally, not delivered" } },
      },
    };
  }
  if (capabilities.auth?.mode === "password") {
    paths["/auth/register"] = {
      post: { responses: { 201: { description: "account" } } },
    };
    paths["/auth/login"] = {
      post: { responses: { 200: { description: "session" } } },
    };
  }
  if (capabilities.auth?.mode === "magic") {
    paths["/auth/magic"] = {
      post: { responses: { 200: { description: "local token, no email" } } },
    };
  }
  const document = {
    openapi: "3.0.3",
    info: { title: name, version: "1" },
    paths,
  };
  if (capabilities.auth) {
    document.components = {
      securitySchemes: {
        bearer: { type: "http", scheme: "bearer" },
      },
    };
  }
  return JSON.stringify(document, null, 2) + "\n";
}

