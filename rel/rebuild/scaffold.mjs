function assertOutsideRepo(directory) {
  const rel = relative(resolve(repoRoot), resolve(directory));
  if (rel === "" || (!rel.startsWith("..") && !isAbsolute(rel)))
    throw new Error("Choose a rebuild directory outside the REE repository.");
}

function quotesIn(spec) {
  const quotes = [];
  for (const feature of spec.features) {
    if (feature.quote?.text) quotes.push(feature.quote.text);
  }
  for (const limitation of spec.limitations) {
    if (limitation.statement?.text) quotes.push(limitation.statement.text);
  }
  return quotes.filter((text) => text.length >= 12);
}

function leaks(value, quotes) {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  return quotes.find((quote) => text.includes(quote)) ?? null;
}

function successStatus(method, codes) {
  const listed = [];
  for (const code of codes ?? []) {
    const value = Number(code);
    if (value === 200 || value === 201) listed.push(value);
  }
  const preferred = method === "POST" ? 201 : 200;
  if (listed.includes(preferred)) return preferred;
  if (listed.length > 0) return listed[0];
  return preferred;
}

function collectionParents(endpoints) {
  const set = new Set();
  let anyItem = false;
  for (const endpoint of endpoints) {
    const path = endpoint?.path;
    if (typeof path !== "string" || !path.includes("{")) continue;
    const match = /^(\/.*)?\/\{([A-Za-z_][A-Za-z0-9_]*)\}$/u.exec(path);
    if (!match || path.split("{").length !== 2) continue;
    anyItem = true;
    const collection = match[1] || "";
    if (collection.startsWith("/")) set.add(collection);
  }
  return { anyItem, set };
}

function actionKind(method, path) {
  const parts = path.split("/").filter(Boolean);
  const last = parts.at(-1) ?? "";
  if (/^login$/iu.test(last)) return { kind: "login" };
  if (/^logout$/iu.test(last)) return { kind: "logout" };
  if (method !== "GET" || parts.length < 2) return null;
  const found = /^findBy([A-Za-z][A-Za-z0-9]*)$/u.exec(last);
  if (found) {
    const raw = found[1];
    return {
      kind: "filter",
      field: raw.charAt(0).toLowerCase() + raw.slice(1),
      collection: "/" + parts.slice(0, -1).join("/"),
    };
  }
  if (/^inventory$/iu.test(last))
    return { kind: "inventory", prefix: "/" + parts.slice(0, -1).join("/") };
  return null;
}

function classifyEndpoint(endpoint, parents = null) {
  const method = String(endpoint?.method ?? "").toUpperCase();
  const path = endpoint?.path;
  if (!HTTP_METHODS.has(method))
    return { ok: false, reason: "method is not built" };
  if (typeof path !== "string" || !path.startsWith("/"))
    return { ok: false, reason: "path template is not expanded" };
  const special = actionKind(method, path);
  if (special) return { ok: true, method, path, item: null, ...special };
  if (!path.includes("{")) {
    if (parents?.anyItem && !parents.set.has(path))
      return {
        ok: false,
        reason: "action endpoint is not a record collection",
      };
    return { ok: true, method, path, item: null };
  }
  const match = /^(\/.*)?\/\{([A-Za-z_][A-Za-z0-9_]*)\}$/u.exec(path);
  if (!match || path.split("{").length !== 2)
    return { ok: false, reason: "path template is not expanded" };
  const collection = match[1] || "";
  if (!collection.startsWith("/") || collection.includes("{"))
    return { ok: false, reason: "path template is not expanded" };
  return {
    ok: true,
    method,
    path,
    item: { param: match[2], collection },
  };
}

function nameEquals(feature, endpoint) {
  if (!feature?.name) return false;
  const summary = endpoint.summary?.text ?? null;
  const operationId = endpoint.operation_id ?? null;
  return (
    feature.name === summary ||
    (operationId !== null && feature.name === operationId)
  );
}

function actionFor(method) {
  if (method === "GET") return "list";
  if (method === "POST") return "create";
  if (method === "PUT") return "replace";
  if (method === "PATCH") return "merge";
  return "remove";
}

function unionParameters(endpointList) {
  const names = [];
  for (const endpoint of endpointList) {
    for (const name of parametersOf(endpoint)) {
      if (!names.includes(name)) names.push(name);
    }
  }
  return names;
}

function unionFields(endpointList) {
  const fields = [];
  for (const endpoint of endpointList) {
    for (const field of endpoint.fields ?? []) {
      if (!field || typeof field.name !== "string" || !field.name) continue;
      const found = fields.find((item) => item.name === field.name);
      if (!found) fields.push({ ...field });
      else if (field.required === true) found.required = true;
    }
  }
  return fields;
}

function modelOf(endpointList) {
  const fields = unionFields(endpointList);
  const names = unionParameters(endpointList);
  if (fields.length === 0) return { parameters: names, fields: [] };
  for (const name of names) {
    if (!fields.some((field) => field.name === name))
      fields.push({ name, required: false, type: "string" });
  }
  return { parameters: fields.map((field) => field.name), fields };
}

function writeRules(model) {
  if (model.fields.some((field) => field.required === true))
    return ["required"];
  if (model.fields.length === 0 && model.parameters.length > 0)
    return ["required"];
  return [];
}

function accountFieldNames(endpoint) {
  const names = parametersOf(endpoint);
  const secret = names.find((name) => /password/iu.test(name)) || "password";
  const identity = names.find((name) => name !== secret) || "username";
  const chosen = [];
  for (const name of [identity, secret]) {
    if (!chosen.includes(name)) chosen.push(name);
  }
  return chosen;
}

function parametersOf(endpoint) {
  const names = [];
  for (const name of endpoint.parameters ?? []) {
    if (typeof name === "string" && name && !names.includes(name))
      names.push(name);
  }
  return names;
}

/**
 * Every spec feature gets a data model, write rules, and CRUD routes.
 * A feature whose name equals an endpoint summary or operation id uses that
 * concrete path. A feature with no such endpoint gets its own collection.
 * Declared GET, POST, PUT, PATCH, and DELETE endpoints are built even when
 * no feature name matches them. A path with one {name} segment gets get,
 * update, and delete on the parent collection. Other path templates stay out.
 */
export function planProduct(spec) {
  const quotes = quotesIn(spec);
  const endpoints = spec.api?.endpoints ?? [];
  const parents = collectionParents(endpoints);
  function buildable(endpoint) {
    return classifyEndpoint(endpoint, parents);
  }
  const behaviors = [];
  const routes = [];
  const resources = [];
  const skipped = [];
  const omitted = [];
  const leftOut = [];
  for (const endpoint of endpoints) {
    const built = buildable(endpoint);
    if (!built.ok) {
      skipped.push({
        method: String(endpoint.method ?? "").toUpperCase(),
        path: typeof endpoint.path === "string" ? endpoint.path : null,
        operation_id: endpoint.operation_id ?? null,
        reason: built.reason,
      });
    }
  }

  function leave(feature, reason) {
    leftOut.push({ id: feature.id, reason });
    behaviors.push({ id: feature.id, status: "unimplemented", handler: null });
  }

  function resourceFor(path, parameters, rules, fields = []) {
    const found = resources.find((item) => item.path === path);
    if (found) {
      let added = false;
      for (const name of parameters) {
        if (!found.parameters.includes(name)) {
          found.parameters.push(name);
          added = true;
        }
        if (!found.model.includes(name)) found.model.push(name);
      }
      for (const field of fields) {
        const existing = found.fields.find((item) => item.name === field.name);
        if (!existing) found.fields.push({ ...field });
        else if (field.required === true) existing.required = true;
      }
      if (added && found.rules.length === 0) {
        for (const rule of rules) {
          if (!found.rules.includes(rule)) found.rules.push(rule);
        }
      }
      return found;
    }
    const resource = {
      id: "c" + resources.length,
      path,
      parameters: [...parameters],
      rules: [...rules],
      fields: fields.map((field) => ({ ...field })),
      model: ["id", ...parameters],
    };
    resources.push(resource);
    return resource;
  }

  function storeRoute(draft) {
    const existing = routes.find(
      (item) => item.method === draft.method && item.path === draft.path,
    );
    if (existing) return existing;
    if (leaks(draft, quotes)) return null;
    const route = { key: "r" + routes.length, ...draft };
    routes.push(route);
    return route;
  }

  function crudFor(resource) {
    const declared = endpoints.filter((endpoint) => {
      const built = buildable(endpoint);
      return built.ok && !built.item && built.path === resource.path;
    });
    const made = [];
    for (const method of CRUD) {
      const endpoint = declared.find(
        (item) => String(item.method ?? "").toUpperCase() === method,
      );
      const parameters =
        method === "GET" || method === "DELETE" ? [] : resource.parameters;
      const draft = {
        method,
        path: resource.path,
        operation_id: endpoint?.operation_id ?? null,
        parameters,
        fields: method === "GET" || method === "DELETE" ? [] : resource.fields,
        declared: Boolean(endpoint),
        success_status: endpoint
          ? successStatus(method, endpoint.response_codes)
          : method === "POST"
            ? 201
            : 200,
        body:
          endpoint?.body === "json" ||
          ((method === "POST" || method === "PUT" || method === "PATCH") &&
            resource.fields.length > 0)
            ? "json"
            : endpoint?.body === "json"
              ? "json"
              : null,
        resource: resource.id,
        action: actionFor(method),
        model: resource.model,
        rules: resource.rules,
      };
      const stored = storeRoute(draft);
      if (!stored) return null;
      made.push(stored);
    }
    ensureItemVerbs(resource);
    return made;
  }

  function itemParam(collection) {
    for (const endpoint of endpoints) {
      const built = buildable(endpoint);
      if (built.ok && built.item && built.item.collection === collection)
        return built.item.param;
    }
    return "id";
  }

  function ensureItemVerbs(resource) {
    const param = itemParam(resource.path);
    const itemPath = `${resource.path}/{${param}}`;
    const verbs = [
      ["GET", "read", []],
      ["PUT", "replace", resource.parameters],
      ["PATCH", "merge", resource.parameters],
      ["DELETE", "remove", []],
    ];
    for (const [method, action, fallbackParameters] of verbs) {
      if (
        routes.some(
          (route) => route.method === method && route.path === itemPath,
        )
      )
        continue;
      const endpoint = endpoints.find((item) => {
        const built = buildable(item);
        return (
          built.ok &&
          built.path === itemPath &&
          built.method === method &&
          built.item
        );
      });
      const sourceFields =
        method === "GET" || method === "DELETE"
          ? []
          : endpoint?.fields?.length
            ? endpoint.fields
            : resource.fields;
      const fields = sourceFields.filter((field) => field?.name !== param);
      const names = (
        endpoint ? parametersOf(endpoint) : fallbackParameters
      ).filter((name) => name !== param);
      storeRoute({
        method,
        path: itemPath,
        path_param: param,
        collection: resource.path,
        operation_id: endpoint?.operation_id ?? null,
        parameters:
          method === "GET" || method === "DELETE"
            ? []
            : fields.length
              ? fields.map((field) => field.name)
              : names,
        fields,
        declared: Boolean(endpoint),
        success_status: endpoint
          ? successStatus(method, endpoint.response_codes)
          : 200,
        body:
          endpoint?.body === "json" ||
          method === "PUT" ||
          method === "PATCH" ||
          fields.length > 0
            ? "json"
            : null,
        resource: resource.id,
        action,
        model: resource.model,
        rules: resource.rules,
      });
    }
  }

  function collectionPath(feature) {
    const raw = String(feature.id ?? "").replace(/^feature:/u, "");
    const base = "/" + slug(raw || "item");
    if (!base.startsWith("/") || base.includes("{") || base === "/")
      return null;
    let path = base;
    let number = 2;
    while (
      resources.some((item) => item.path === path) ||
      endpoints.some((endpoint) => endpoint.path === path)
    ) {
      path = `${base}-${number}`;
      number += 1;
    }
    return path;
  }

  function parentResource(collection) {
    const onPath = endpoints.filter((endpoint) => {
      const built = buildable(endpoint);
      return built.ok && !built.item && built.path === collection;
    });
    const model = modelOf(onPath);
    return resourceFor(
      collection,
      model.parameters,
      writeRules(model),
      model.fields,
    );
  }

  function itemRoute(endpoint, built, resource) {
    const writing = built.method !== "GET" && built.method !== "DELETE";
    const names = writing
      ? parametersOf(endpoint).filter((name) => name !== built.item.param)
      : [];
    const fields = writing
      ? endpoint.fields?.length
        ? endpoint.fields.filter((field) => field.name !== built.item.param)
        : names.map((name) => ({ name, required: false, type: "string" }))
      : [];
    return storeRoute({
      method: built.method,
      path: built.path,
      path_param: built.item.param,
      collection: built.item.collection,
      operation_id: endpoint.operation_id ?? null,
      parameters: fields.length ? fields.map((field) => field.name) : names,
      fields,
      declared: true,
      success_status: successStatus(built.method, endpoint.response_codes),
      body: endpoint.body === "json" ? "json" : null,
      resource: resource.id,
      action:
        built.method === "GET"
          ? "read"
          : built.method === "POST"
            ? "merge"
            : actionFor(built.method),
      model: resource.model,
      rules: resource.rules,
    });
  }

  function ensureItem(endpoint) {
    const built = buildable(endpoint);
    if (!built.item) return null;
    const existing = routes.find(
      (route) => route.method === built.method && route.path === built.path,
    );
    if (existing) return existing;
    const resource = parentResource(built.item.collection);
    if (!crudFor(resource)) return null;
    return itemRoute(endpoint, built, resource);
  }

  function skipEndpoint(endpoint, built, reason) {
    skipped.push({
      method: built.method,
      path: built.path,
      operation_id: endpoint.operation_id ?? null,
      reason,
    });
    return null;
  }

  function addAccountNames(resource, names) {
    const schema = resource.fields.length > 0;
    for (const name of names) {
      if (!resource.parameters.includes(name)) resource.parameters.push(name);
      if (!resource.model.includes(name)) resource.model.push(name);
      if (schema && !resource.fields.some((field) => field.name === name))
        resource.fields.push({ name, required: false, type: "string" });
    }
    for (const route of routes) {
      if (route.resource !== resource.id) continue;
      if (!["create", "replace", "merge"].includes(route.action)) continue;
      for (const name of names) {
        if (!route.parameters.includes(name)) route.parameters.push(name);
        if (!route.model.includes(name)) route.model.push(name);
        if (
          schema &&
          route.fields.length > 0 &&
          !route.fields.some((field) => field.name === name)
        )
          route.fields.push({ name, required: false, type: "string" });
      }
    }
  }

  function collectionForInventory(prefix) {
    const found = new Set();
    for (const endpoint of endpoints) {
      const built = buildable(endpoint);
      if (!built.ok || built.kind) continue;
      if (built.item && built.item.collection.startsWith(prefix + "/"))
        found.add(built.item.collection);
      else if (!built.item && built.path.startsWith(prefix + "/"))
        found.add(built.path);
    }
    return (
      [...found].sort((left, right) => right.length - left.length)[0] ?? null
    );
  }

  function actionRoute(endpoint, built, resource, extra) {
    return storeRoute({
      method: built.method,
      path: built.path,
      operation_id: endpoint.operation_id ?? null,
      parameters: extra.parameters ?? [],
      fields: [],
      declared: true,
      success_status: successStatus(built.method, endpoint.response_codes),
      body: endpoint.body === "json" ? "json" : null,
      resource: resource.id,
      collection: extra.collection,
      action: built.kind,
      model: resource.model,
      rules: resource.rules,
      filter_field: extra.filter_field ?? null,
      group_field: extra.group_field ?? null,
    });
  }

  function addAction(endpoint, built) {
    const existing = routes.find(
      (route) => route.method === built.method && route.path === built.path,
    );
    if (existing) return existing;
    if (built.kind === "login" || built.kind === "logout") {
      const parts = built.path.split("/").filter(Boolean);
      parts.pop();
      const collection = parts.length ? `/${parts.join("/")}` : "";
      if (!collection.startsWith("/"))
        return skipEndpoint(endpoint, built, "login has no account collection");
      const resource = parentResource(collection);
      const accountNames =
        built.kind === "login" ? accountFieldNames(endpoint) : [];
      if (accountNames.length) addAccountNames(resource, accountNames);
      if (!crudFor(resource))
        return skipEndpoint(
          endpoint,
          built,
          "structural fields repeated a spec quote",
        );
      if (accountNames.length) addAccountNames(resource, accountNames);
      return actionRoute(endpoint, built, resource, {
        collection,
        parameters:
          built.kind === "login" ? accountNames : parametersOf(endpoint),
      });
    }
    if (built.kind === "filter") {
      const resource = parentResource(built.collection);
      if (!crudFor(resource))
        return skipEndpoint(
          endpoint,
          built,
          "structural fields repeated a spec quote",
        );
      return actionRoute(endpoint, built, resource, {
        collection: built.collection,
        parameters: parametersOf(endpoint),
        filter_field: built.field,
      });
    }
    const collection = collectionForInventory(built.prefix);
    if (!collection)
      return skipEndpoint(
        endpoint,
        built,
        "inventory has no record collection to count",
      );
    const resource = parentResource(collection);
    if (!crudFor(resource))
      return skipEndpoint(
        endpoint,
        built,
        "structural fields repeated a spec quote",
      );
    return actionRoute(endpoint, built, resource, {
      collection,
      group_field: resource.model.includes("status") ? "status" : null,
    });
  }

  for (const feature of spec.features ?? []) {
    if (leaks(feature.id, quotes)) {
      omitted.push(feature.id);
      leftOut.push({
        id: feature.id,
        reason: "feature id would repeat a spec quote",
      });
      continue;
    }
    const named = endpoints.filter((endpoint) => nameEquals(feature, endpoint));
    const buildableHits = named.filter((endpoint) => buildable(endpoint).ok);
    const blockedHits = named.filter((endpoint) => !buildable(endpoint).ok);
    if (buildableHits.length === 0 && blockedHits.length > 0) {
      leave(feature, buildable(blockedHits[0]).reason);
      continue;
    }
    if (buildableHits.length > 0) {
      const concrete = buildableHits.filter((endpoint) => {
        const built = buildable(endpoint);
        return !built.item && !built.kind;
      });
      const actions = buildableHits.filter(
        (endpoint) => buildable(endpoint).kind,
      );
      const items = buildableHits.filter(
        (endpoint) => buildable(endpoint).item,
      );
      for (const endpoint of actions) addAction(endpoint, buildable(endpoint));
      if (concrete.length === 0 && items.length === 0) {
        const first = actions[0];
        const stored = first
          ? routes.find(
              (route) =>
                route.method === String(first.method).toUpperCase() &&
                route.path === first.path,
            )
          : null;
        if (!stored) {
          leave(feature, "structural fields repeated a spec quote");
          continue;
        }
        behaviors.push({
          id: feature.id,
          status: "implemented",
          handler: stored.key,
        });
        continue;
      }
      if (concrete.length === 0) {
        const stored = ensureItem(
          items.find(
            (endpoint) => String(endpoint.method).toUpperCase() === "GET",
          ) ?? items[0],
        );
        for (const endpoint of items) ensureItem(endpoint);
        if (!stored) {
          leave(feature, "structural fields repeated a spec quote");
          continue;
        }
        behaviors.push({
          id: feature.id,
          status: "implemented",
          handler: stored.key,
        });
        continue;
      }
      const preferred =
        concrete.find(
          (endpoint) => String(endpoint.method).toUpperCase() === "POST",
        ) ?? concrete[0];
      for (const endpoint of items) ensureItem(endpoint);
      const path = buildable(preferred).path;
      const onPath = endpoints.filter((endpoint) => {
        const built = buildable(endpoint);
        return built.ok && !built.item && built.path === path;
      });
      const model = modelOf(onPath);
      const resource = resourceFor(
        path,
        model.parameters,
        writeRules(model),
        model.fields,
      );
      const made = crudFor(resource);
      if (!made) {
        leave(feature, "structural fields repeated a spec quote");
        continue;
      }
      const handler =
        made.find(
          (route) =>
            route.method === String(preferred.method).toUpperCase() &&
            route.path === path,
        ) ?? made[0];
      behaviors.push({
        id: feature.id,
        status: "implemented",
        handler: handler.key,
      });
      continue;
    }
    const path = collectionPath(feature);
    if (!path) {
      leave(feature, "a safe collection path could not be formed");
      continue;
    }
    if (leaks(path, quotes)) {
      leave(feature, "a safe path would repeat a spec quote");
      continue;
    }
    const resource = resourceFor(
      path,
      ["label"],
      ["required", "unique", "max-length"],
    );
    const made = crudFor(resource);
    if (!made) {
      leave(feature, "structural fields repeated a spec quote");
      continue;
    }
    const handler = made.find((route) => route.action === "create") ?? made[0];
    behaviors.push({
      id: feature.id,
      status: "implemented",
      handler: handler.key,
    });
  }

  for (const endpoint of endpoints) {
    const built = buildable(endpoint);
    if (!built.ok) continue;
    if (built.kind) {
      addAction(endpoint, built);
      continue;
    }
    if (built.item) {
      if (!ensureItem(endpoint)) {
        skipped.push({
          method: built.method,
          path: built.path,
          operation_id: endpoint.operation_id ?? null,
          reason: "structural fields repeated a spec quote",
        });
      }
      continue;
    }
    if (routes.some((route) => route.path === built.path)) continue;
    const onPath = endpoints.filter((item) => {
      const itemBuilt = buildable(item);
      return itemBuilt.ok && itemBuilt.path === built.path;
    });
    const model = modelOf(onPath);
    const resource = resourceFor(
      built.path,
      model.parameters,
      writeRules(model),
      model.fields,
    );
    if (!crudFor(resource)) {
      skipped.push({
        method: built.method,
        path: built.path,
        operation_id: null,
        reason: "structural fields repeated a spec quote",
      });
    }
  }

  const unmatched = endpoints.filter((endpoint) => {
    if (!buildable(endpoint).ok) return false;
    return !(spec.features ?? []).some((feature) =>
      nameEquals(feature, endpoint),
    );
  });
  const endpointBuilt = endpoints.filter((endpoint) => {
    const built = buildable(endpoint);
    return (
      built.ok &&
      routes.some(
        (route) => route.method === built.method && route.path === built.path,
      )
    );
  }).length;
  return {
    behaviors,
    routes,
    skipped,
    unmatched,
    omitted,
    leftOut,
    endpointBuilt,
  };
}

function routeLine(route) {
  if (route.action === "login")
    return `- ${route.method} ${route.path} issues a token after a hashed password check.`;
  if (route.action === "logout")
    return `- ${route.method} ${route.path} revokes the current token.`;
  if (route.action === "filter")
    return `- ${route.method} ${route.path} filters ${route.collection} by ${route.filter_field}.`;
  if (route.action === "inventory")
    return `- ${route.method} ${route.path} counts records in ${route.collection}${route.group_field ? ` by ${route.group_field}` : ""}.`;
  const params = route.parameters.length
    ? ` Fields: ${route.parameters.join(", ")}.`
    : "";
  const body = route.body === "json" ? " JSON body accepted." : "";
  const item = route.path_param
    ? ` Path parameter ${route.path_param} uses the parent collection.`
    : "";
  const operation = route.operation_id
    ? ` Operation id: ${route.operation_id}.`
    : "";
  return `- ${route.method} ${route.path} returns ${route.success_status}.${params}${body}${item}${operation}`;
}

function endpointCoverageLine(plan) {
  const built = plan.endpointBuilt ?? 0;
  const total = built + (plan.skipped?.length ?? 0);
  const ratio = total === 0 ? "none" : (built / total).toFixed(3);
  return `Endpoint coverage: ${built} of ${total} (${ratio}). That count is endpoints, not improvements, and it is not a percentage of the original product.`;
}

function endpointLines(plan) {
  const lines = ["## Endpoints", ""];
  if ((plan.skipped ?? []).length === 0) {
    lines.push("Not built:", "- none");
    return lines;
  }
  lines.push("Not built:");
  for (const item of plan.skipped) {
    lines.push(
      `- ${item.method || "(no method)"} ${item.path ?? "(no path)"}: ${item.reason}.`,
    );
  }
  return lines;
}

function endpointLine(endpoint) {
  const method = String(endpoint.method ?? "").toUpperCase();
  const operation = endpoint.operation_id ? ` (${endpoint.operation_id})` : "";
  return `- ${method} ${endpoint.path}${operation}`;
}

function featureLabel(feature, spec) {
  const name = typeof feature?.name === "string" ? feature.name : "";
  const id = feature?.id ?? "feature";
  if (!name) return id;
  const quotes = quotesIn(spec);
  const brand = String(spec.target?.name ?? "").trim();
  if (quotes.some((quote) => name.includes(quote))) return id;
  if (brand && name.includes(brand)) return id;
  return `${id} (${name})`;
}

function markedFeature(feature, spec) {
  const label = featureLabel(feature, spec);
  return feature?.origin === "improvement" ? `${label} (improvement)` : label;
}

function featureLines(spec, plan) {
  const byId = new Map(
    (spec.features ?? []).map((feature) => [feature.id, feature]),
  );
  const implemented = plan.behaviors.filter(
    (item) => item.status === "implemented",
  );
  const lines = ["## Features", ""];
  lines.push("Implemented:");
  if (implemented.length === 0) lines.push("- none");
  else {
    for (const item of implemented) {
      const feature = byId.get(item.id) ?? item;
      lines.push(`- ${markedFeature(feature, spec)}`);
    }
  }
  lines.push("", "Left out:");
  if ((plan.leftOut ?? []).length === 0) lines.push("- none");
  else {
    for (const item of plan.leftOut) {
      const feature = byId.get(item.id) ?? item;
      lines.push(`- ${markedFeature(feature, spec)}: ${item.reason}.`);
    }
  }
  return lines;
}

