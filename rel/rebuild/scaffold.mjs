import { createHash, randomBytes } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assertValidBehaviorSpec } from "../outside-in/validate.mjs";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));

export const REBUILD_SCHEMA = "ree.rebuild.provenance.v1";

function assertOutsideRepo(directory) {
  const rel = relative(resolve(repoRoot), resolve(directory));
  if (rel === "" || (!rel.startsWith("..") && !isAbsolute(rel)))
    throw new Error("Choose a rebuild directory outside the REE repository.");
}

function quotesIn(spec) {
  const quotes = [];
  for (const feature of spec.features) {
    if (feature.quote?.text) quotes.push(feature.quote.text);
  }
  for (const limitation of spec.limitations) {
    if (limitation.statement?.text) quotes.push(limitation.statement.text);
  }
  return quotes.filter((text) => text.length >= 12);
}

function sourceText(spec) {
  const behaviors = spec.features.map((feature) => ({
    id: feature.id,
    name: feature.name,
    status: "declared",
  }));
  return [
    "// Generated by REE rebuild. Feature ids and names only.",
    "// Quotes and competitor source are not copied here.",
    "export const behaviors = " + JSON.stringify(behaviors, null, 2) + ";",
    "",
  ].join("\n");
}

function testText(spec) {
  const cases = spec.features
    .map(
      (feature) =>
        `test(${JSON.stringify("accounted " + feature.id)}, () => {
  const declared = behaviors.find((item) => item.id === ${JSON.stringify(feature.id)});
  assert.ok(declared, ${JSON.stringify(feature.id)});
  assert.equal(declared.name, ${JSON.stringify(feature.name)});
  assert.equal(declared.status, "declared");
});`,
    )
    .join("\n\n");
  return [
    'import assert from "node:assert/strict";',
    'import { readFileSync } from "node:fs";',
    'import { test } from "node:test";',
    'import { behaviors } from "../src/behaviors.mjs";',
    "",
    "const spec = JSON.parse(",
    '  readFileSync(new URL("../behavior-spec.json", import.meta.url), "utf8"),',
    ");",
    "const source = readFileSync(",
    '  new URL("../src/behaviors.mjs", import.meta.url),',
    '  "utf8",',
    ");",
    "",
    cases,
    "",
    'test("scaffold source does not contain spec quotes", () => {',
    "  const quotes = [];",
    "  for (const feature of spec.features) {",
    "    if (feature.quote?.text && feature.quote.text.length >= 12)",
    "      quotes.push(feature.quote.text);",
    "  }",
    "  for (const limitation of spec.limitations) {",
    "    if (limitation.statement?.text && limitation.statement.text.length >= 12)",
    "      quotes.push(limitation.statement.text);",
    "  }",
    "  for (const quote of quotes) assert.equal(source.includes(quote), false, quote);",
    "});",
    "",
  ].join("\n");
}

/**
 * Write a new folder whose source is a feature registry.
 * The spec is stored beside it. Original code is neither read nor copied.
 */
export function scaffoldRebuild({
  spec: input,
  productName,
  outDir,
  now = new Date(),
}) {
  if (typeof productName !== "string" || !productName.trim())
    throw new Error("A new product name is required.");
  if (
    productName.trim().toLowerCase() ===
    String(input?.target?.name ?? "")
      .trim()
      .toLowerCase()
  )
    throw new Error(
      "The new product name must differ from the spec target name.",
    );
  const spec = assertValidBehaviorSpec(input);
  if (!outDir) throw new Error("An output directory is required.");
  assertOutsideRepo(outDir);
  const leaked = quotesIn(spec).find((quote) => productName.includes(quote));
  if (leaked) throw new Error("The product name contains a spec quote.");
  const specBytes = JSON.stringify(spec);
  const specSha = createHash("sha256").update(specBytes).digest("hex");
  const buildId = "bld_" + randomBytes(8).toString("hex");
  const source = sourceText(spec);
  const readme = [
    `# ${productName.trim()}`,
    "",
    "Clean-room scaffold. Feature names are declared from a behavior spec.",
    "This folder does not implement those features and does not contain competitor source.",
    "",
    "```sh",
    "npm test",
    "```",
    "",
    "The declaration tests check that each spec feature id is listed and that quotes",
    "were not copied into src/.",
    "",
  ].join("\n");
  const provenance = {
    schema_version: REBUILD_SCHEMA,
    build_id: buildId,
    generated_at: now.toISOString(),
    product_name: productName.trim(),
    spec_schema: spec.schema_version,
    spec_sha256: specSha,
    spec_target_recorded_in: "provenance.json",
    clean_room: true,
    clean_room_statement: spec.clean_room_statement,
    original_code_viewed: false,
    original_code_copied: false,
    similarity: spec.similarity,
    sources: spec.sources.map((source) => ({
      url: source.url,
      role: source.role,
      fetched_at: source.fetched_at,
      sha256: source.sha256,
    })),
    generator: "ree-rebuild",
  };
  const manifest = {
    name: slug(productName),
    private: true,
    type: "module",
    description:
      "Clean-room scaffold generated by REE. No original source was copied.",
    scripts: { test: "node --test" },
    license: "UNLICENSED",
  };
  const lock = {
    name: manifest.name,
    lockfileVersion: 3,
    requires: true,
    packages: { "": { name: manifest.name } },
  };
  mkdirSync(join(outDir, "src"), { recursive: true });
  mkdirSync(join(outDir, "test"), { recursive: true });
  writeFileSync(
    join(outDir, "package.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  writeFileSync(
    join(outDir, "package-lock.json"),
    JSON.stringify(lock, null, 2) + "\n",
  );
  writeFileSync(join(outDir, "README.md"), readme);
  writeFileSync(join(outDir, "src/behaviors.mjs"), source);
  writeFileSync(join(outDir, "test/accounted.test.mjs"), testText(spec));
  writeFileSync(
    join(outDir, "behavior-spec.json"),
    JSON.stringify(spec, null, 2) + "\n",
  );
  writeFileSync(
    join(outDir, "provenance.json"),
    JSON.stringify(provenance, null, 2) + "\n",
  );
  writeFileSync(
    join(outDir, "PROVENANCE.md"),
    [
      "# Provenance",
      "",
      provenance.clean_room_statement,
      "",
      "Original code viewed: no",
      "Original code copied: no",
      `Spec sha256: ${specSha}`,
      `Similarity flagged: ${spec.similarity.flagged ? "yes" : "no"}`,
      "",
      "Sources:",
      ...provenance.sources.map((item) => `- ${item.url} (${item.fetched_at})`),
      "",
    ].join("\n"),
  );
  return {
    build_id: buildId,
    out_dir: outDir,
    provenance,
    feature_count: spec.features.length,
  };
}

function slug(name) {
  const value = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return value || "rebuild";
}
